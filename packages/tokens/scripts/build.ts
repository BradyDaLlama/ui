import { mkdirSync, writeFileSync } from 'node:fs';
import { tokens } from '../src/index';

const { colors, fonts, text, sizes, radius, borders, shadows, motion } = tokens;

function vars(prefix: string, record: Record<string, string | number>, map = (v: string | number) => String(v)) {
    return Object.entries(record).map(([key, value]) => `    --${prefix}-${key}: ${map(value)};`);
}

const scaled = (modifier: string) => (v: string | number) => `calc(${v}rem * var(--${modifier}, 1))`;

const lines = [
    ...vars('color', colors),
    ...vars('font', fonts),
    ...vars('text', text, scaled('font-modifier')),
    ...vars('size', sizes, scaled('size-modifier')),
    ...vars('radius', radius),
    ...vars('border', borders),
    ...vars('shadow', shadows),
    ...vars('duration', { fast: motion.fast, base: motion.base, slow: motion.slow }),
    `    --ease-elastic: ${motion.elastic};`,
];

const header = '/* Generated by @bradydallama/tokens. Do not edit. */\n';

mkdirSync('dist', { recursive: true });

// Plain custom properties for any stack.
writeFileSync(
    'dist/tokens.css',
    `${header}:root {\n    --font-modifier: 1;\n    --size-modifier: 1;\n${lines.join('\n')}\n}\n`,
);

// Tailwind v4: registers the same values so utilities like bg-primary / text-md / size-sm exist.
writeFileSync(
    'dist/theme.css',
    `${header}:root {\n    --font-modifier: 1;\n    --size-modifier: 1;\n}\n\n@theme {\n${lines.join('\n')}\n}\n`,
);

// Raw values for native targets (Android widget, Wear OS tile).
writeFileSync('dist/tokens.json', JSON.stringify(tokens, null, 4) + '\n');

console.log('tokens: wrote dist/tokens.css, dist/theme.css, dist/tokens.json');
